    private void salvarDados() {
        try (BufferedWriter writer = new BufferedWriter(new FileWriter("C:\\Users\\chu_b\\OneDrive\\Documentos\\NetBeansProjects\\InterfaceJava\\produtos.txt"))) {
            DefaultTableModel dtmProdutos = (DefaultTableModel) jTProdutos.getModel();
            for (int i = 0; i < dtmProdutos.getRowCount(); i++) {
                String desc = dtmProdutos.getValueAt(i, 0).toString();
                String nome = dtmProdutos.getValueAt(i, 1).toString();
                String quantidade = dtmProdutos.getValueAt(i, 2).toString();
                String data = dtmProdutos.getValueAt(i, 3).toString();
                
                // Escreve a linha no arquivo
                writer.write(desc + ";" + nome + ";" + quantidade + ";" + data);
                writer.newLine(); // Adiciona uma nova linha
            }
            JOptionPane.showMessageDialog(this, "Dados salvos com sucesso!");
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Erro ao salvar os dados: " + e.getMessage());
        }
    }//GEN-LAST:event_jButton4ActionPerformed

