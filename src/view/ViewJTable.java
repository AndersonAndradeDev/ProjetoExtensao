    private void carregarDados() {
    try (BufferedReader reader = new BufferedReader(new FileReader("C:\\Users\\chu_b\\OneDrive\\Documentos\\NetBeansProjects\\JavaApplication1\\produtos.txt"))) {
        String linha;
        DefaultTableModel dtmProdutos = (DefaultTableModel) jTProdutos.getModel();
        while ((linha = reader.readLine()) != null) {
            String[] dados = linha.split(";");
            dtmProdutos.addRow(dados);
        }
    } catch (IOException e) {
        JOptionPane.showMessageDialog(this, "Erro ao carregar os dados: " + e.getMessage());
    }
}
